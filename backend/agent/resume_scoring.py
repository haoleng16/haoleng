"""Resume scoring prompt helpers."""

RUBRIC = """一、JD匹配度，满分30分
评估候选人的技能、经验、行业背景、岗位职责是否与JD匹配。
评分规则：
- 25-30分：与JD高度匹配，核心技能和主要职责都有明确经历支撑。
- 18-24分：较匹配，大部分核心要求满足，但部分要求缺失或证据不足。
- 10-17分：一般匹配，只满足部分要求，岗位适配度有限。
- 0-9分：匹配度较低，核心要求明显缺失。

二、核心能力，满分25分
评估候选人是否具备岗位真正需要的能力。
注意：核心能力不是简单关键词，而是“技能 + 使用场景 + 实际结果”。
评分规则：
- 21-25分：核心能力明确，有具体项目、职责或成果支撑。
- 15-20分：具备一定核心能力，但深度或证据一般。
- 8-14分：能力描述较泛，缺少实际场景支撑。
- 0-7分：核心能力不明显，难以证明胜任岗位。

三、项目/作品质量，满分20分
评估候选人是否有真实项目、作品、成果数据或可验证产出。
评分规则：
- 17-20分：项目真实完整，职责清晰，有数据、成果或上线结果。
- 12-16分：项目较完整，但成果数据不够明确。
- 6-11分：项目描述较浅，更多是参与而非负责。
- 0-5分：缺少项目/作品，或项目真实性和价值较弱。

四、稳定性，满分10分
评估候选人的工作时长、跳槽频率、空窗期和职业连续性。
评分规则：
- 9-10分：工作经历稳定，单段经历较长，职业路径连续。
- 7-8分：整体较稳定，有少量短期经历但不严重。
- 4-6分：存在多段短期经历、空窗期或职业方向变化。
- 0-3分：频繁跳槽明显，或经历断裂严重。

参考工作时长：
- 1个月以内：稳定性较差
- 1-3个月：稳定性偏弱
- 3-6个月：稳定性一般
- 6-12个月：基本可接受
- 1-2年：较稳定
- 2年以上：稳定
- 3年以上：非常稳定"""


def build_resume_scoring_prompt(jd_text: str, resume_text: str) -> str:
    jd = clean_jd_text(jd_text) or "用户未提供 JD。JD匹配度请按证据不足保守评分，并在修改意见中提醒补充目标JD。"
    return f"""你是严格的招聘简历评估助手。请根据 JD 和 OCR 提取出的简历内容评分。

重要要求：
1. 最终只输出评分结果和修改意见。
2. 不要展示、复述、摘抄或泄露 OCR 提取出的简历原文。
3. 每个维度必须给出分数、扣分原因和可执行修改建议。
4. 最后给出总分，满分 85 分。
5. 如果证据不足，要明确写“证据不足”，不要编造经历、项目、数据。

评分标准：
{RUBRIC}

输出格式：
## 简历评分
| 维度 | 得分 | 满分 | 评价 |
| --- | ---: | ---: | --- |
| JD匹配度 | x | 30 | ... |
| 核心能力 | x | 25 | ... |
| 项目/作品质量 | x | 20 | ... |
| 稳定性 | x | 10 | ... |

**总分：x/85**

## 主要问题
- ...

## 修改意见
- ...

JD内容：
{jd}

OCR简历内容（仅供内部评分，禁止在最终回复中展示原文）：
{resume_text.strip()}"""


def build_upload_message(text: str, filenames: list[str]) -> str:
    lines = []
    if text.strip():
        lines.append(text.strip())
    if filenames:
        lines.append("已上传简历PDF：" + "、".join(filenames))
    return "\n".join(lines) or "已上传简历PDF，请按评分标准分析。"


def clean_jd_text(text: str) -> str:
    lines = [
        line.strip()
        for line in text.splitlines()
        if line.strip() and not line.strip().startswith("已上传简历PDF：")
    ]
    return "\n".join(lines).strip()
